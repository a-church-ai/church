/**
 * The daily cap, read from git rather than from a state file.
 *
 * The alternative was a JSON file under app/data/. That does not survive a
 * GitHub Actions run, so it would have to be committed, which adds a commit on
 * every run and a file that can disagree with what was actually published.
 *
 * Git history already is the record of what was published. Counting the
 * pieces the songwriter committed in the last day needs no new state, cannot
 * drift from reality, and is correct on a laptop and in CI without
 * configuration.
 */

const { execFile } = require('child_process');
const { promisify } = require('util');
const path = require('path');

const { PROJECT_ROOT } = require('./paths');

const execFileAsync = promisify(execFile);

async function git(args) {
  const { stdout } = await execFileAsync('git', args, {
    cwd: PROJECT_ROOT,
    maxBuffer: 8 * 1024 * 1024,
  });
  return stdout;
}

/**
 * The pieces the songwriter added within the window, as the documents its
 * commits created (each piece is one document, and a chant has no song).
 * Its commits are known by the line every one of them carries, so a person's
 * edit to a song or a document is not counted as a new piece; until
 * 2026-10-14 the cap counted any song.md committed, which counted hand edits
 * to lyrics and would not have counted a chant at all.
 */
const SONGWRITER_MARK = 'Generated by scripts/generate-song.js';

async function piecesWrittenSince(since = '24 hours ago') {
  let stdout;
  try {
    stdout = await git(['log', `--since=${since}`, `--grep=${SONGWRITER_MARK}`, '--fixed-strings',
      '--diff-filter=A', '--name-only', '--pretty=format:', '--', 'docs/']);
  } catch (error) {
    // A shallow clone or a repository with no commits yet. Returning zero would
    // silently disable the cap, so surface it and let the caller decide.
    throw new Error(`Could not read git history for the daily cap: ${error.message}`);
  }
  const pieces = new Set(
    stdout.split('\n')
      .map((line) => line.trim())
      .filter((line) => line.endsWith('.md') && !/\/README\.md$/i.test(line)),
  );
  return [...pieces];
}

const slugOf = (file) => path.basename(file, '.md');

/** Titles written recently, so the decide stage can avoid repeating itself. */
async function recentTitles(since = '14 days ago') {
  return (await piecesWrittenSince(since)).map(slugOf);
}

/**
 * Is there room to write another piece today.
 *
 * `limit` is the number of pieces per rolling 24 hours, not per calendar day: a
 * calendar boundary would let a run at 23:50 and another at 00:10 both pass.
 */
async function canWriteAnother(limit) {
  const written = await piecesWrittenSince('24 hours ago');
  return {
    ok: written.length < limit,
    written: written.length,
    limit,
    slugs: written.map(slugOf),
  };
}

module.exports = { piecesWrittenSince, recentTitles, canWriteAnother, SONGWRITER_MARK };
