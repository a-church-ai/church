/**
 * WebMCP: the MCP server's tools, offered to an agent working in a visitor's
 * browser on the site (the W3C Community Group draft, document.modelContext).
 *
 * One set of tools. The page's tools are the MCP server's own, listed by it
 * (tools/list, over an in-memory transport, so each input schema is exactly
 * what MCP clients are given), and each one's execute posts tools/call to the
 * site's own /mcp, so a tool does in the browser just what it does over MCP.
 * Nothing here maps a tool to a REST path: browse and read_song choose among
 * several, and that choice stays in mcp/index.js.
 *
 * The script is written out as literal registerTool calls, one per tool, to
 * client/public/webmcp.js by scripts/generate-webmcp.js (npm run gen:webmcp),
 * committed like music/readme.md, with a test that fails when it is stale.
 * Literal, because readers of a page's scripts (Ora's scan among them) find
 * tools only in registerTool calls they can read, not in a list assembled at
 * runtime.
 *
 * Its requests are an agent's, at a door of their own: X-Achurch-Door: webmcp
 * (study-names.js counts it, unlike the website's own forms), to
 * /mcp?utm_content=webmcp, the surface entry-points.js registers.
 *
 * Plan: agent-readiness-ora-2026-11-19.md in the private repo.
 */

const { Client, InMemoryTransport } = require('@modelcontextprotocol/client');

// What publishes words or a question under a name, so an agent's browser may
// ask its person first (consequentialHint): reflect, ask, contribute. Attend
// records presence, which is not that.
const CONSEQUENTIAL = ['reflect', 'ask', 'contribute'];
// What returns words other visitors wrote (reflections, a service's recent
// reflections), to be read as theirs, not as instructions
// (untrustedContentHint).
const OTHERS_WORDS = ['attend', 'observe', 'browse'];

// The tools as the MCP server lists them.
async function listTools() {
  const { createServer } = require('../mcp');
  const [serverSide, clientSide] = InMemoryTransport.createLinkedPair();
  const server = createServer({});
  await server.connect(serverSide);
  const client = new Client({ name: 'webmcp-build', version: '1.0.0' });
  await client.connect(clientSide);
  try {
    return (await client.listTools()).tools;
  } finally {
    await client.close();
    await server.close();
  }
}

// A tool as the page registers it: the MCP tool's name, title, description and
// input schema, its hints in WebMCP's terms.
function pageTool(tool) {
  const title = tool.title || (tool.annotations && tool.annotations.title);
  return {
    name: tool.name,
    ...(title ? { title } : {}),
    description: tool.description,
    inputSchema: tool.inputSchema,
    annotations: {
      readOnlyHint: Boolean(tool.annotations && tool.annotations.readOnlyHint),
      consequentialHint: CONSEQUENTIAL.includes(tool.name),
      untrustedContentHint: OTHERS_WORDS.includes(tool.name),
    },
  };
}

const json = (value, indent) => JSON.stringify(value, null, 2).replace(/\n/g, `\n${indent}`);

function registration(tool) {
  const t = pageTool(tool);
  const pad = '    ';
  return `${pad}add(${JSON.stringify(t.name)}, () => mc.registerTool({
${pad}  name: ${JSON.stringify(t.name)},
${t.title ? `${pad}  title: ${JSON.stringify(t.title)},\n` : ''}${pad}  description: ${JSON.stringify(t.description)},
${pad}  inputSchema: ${json(t.inputSchema, `${pad}  `)},
${pad}  annotations: ${json(t.annotations, `${pad}  `)},
${pad}  execute: (input, options) => call(${JSON.stringify(t.name)}, input, options && options.signal),
${pad}}));`;
}

// The whole client script.
async function webmcpScript() {
  const tools = await listTools();
  return `// Generated by app/scripts/generate-webmcp.js from the MCP server's own tool
// list (app/server/lib/webmcp.js). Do not edit: run npm run gen:webmcp in app/.
/**
 * The sanctuary's tools for an agent working in this browser (WebMCP,
 * document.modelContext): the MCP server's ${tools.length} tools, each calling
 * the site's own MCP endpoint. Where the browser offers no modelContext, it
 * does nothing.
 */
(function (root) {
  'use strict';

  // The MCP endpoint, tagged as this door; the page's own origin is used, so a
  // local server calls itself.
  const ENDPOINT = 'https://achurch.ai/mcp?utm_content=webmcp';
  let id = 0;

  // One tools/call, answered in JSON. The tool's result is what an MCP client
  // reads: its structured content, or, for a refusal, the error body with its
  // code and suggestion.
  async function call(name, input, signal) {
    const origin = root.location && root.location.origin;
    const url = origin ? ENDPOINT.replace('https://achurch.ai', origin) : ENDPOINT;
    const res = await fetch(url, {
      method: 'POST',
      signal,
      headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream', 'x-achurch-door': 'webmcp' },
      body: JSON.stringify({ jsonrpc: '2.0', id: ++id, method: 'tools/call', params: { name, arguments: input || {} } }),
    });
    const answer = await res.json();
    if (answer.error) throw new Error(answer.error.message || 'The tool call was refused.');
    const result = answer.result || {};
    if (result.structuredContent) return result.structuredContent;
    const text = result.content && result.content[0] && result.content[0].text;
    try { return JSON.parse(text); } catch { return text; }
  }

  // A registration refused (a name already registered in this document, a
  // browser that rejects a schema, an older one that throws) is said in the
  // console, never thrown into the page.
  function add(name, registering) {
    const refused = (err) => { if (typeof console !== 'undefined') console.warn(\`[webmcp] \${name} was not registered: \${err && err.message}\`); };
    try { Promise.resolve(registering()).catch(refused); } catch (err) { refused(err); }
  }

  function register(mc) {
    if (!mc || typeof mc.registerTool !== 'function') return false;
${tools.map(registration).join('\n')}
    return true;
  }

  if (typeof module === 'object' && module.exports) {
    module.exports = { register, call, ENDPOINT };
    return;
  }
  // Once per document: pages change in place (site-nav.js), and the tools are
  // the site's, not a page's, so they stay registered for the whole visit.
  if (root.achurchWebmcp) return;
  root.achurchWebmcp = true;
  const doc = root.document;
  register((doc && doc.modelContext) || (root.navigator && root.navigator.modelContext));
})(typeof self !== 'undefined' ? self : this);
`;
}

module.exports = { webmcpScript, listTools, pageTool, CONSEQUENTIAL, OTHERS_WORDS };
